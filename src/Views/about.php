<h1>サークルについて</h1>

<h2>サークル概要</h2>
<p>九産模型愛好会（KSMC）は九州産業大学の学生によって立ち上げられた任意団体(サークル)です。</p>
<p>2024年6月から活動を始め、現在は九州内にある各大学の模型サークルからなる組織、九州学生模型連合にも所属しています。当愛好会には毎年個性豊かなメンバーが集まり、ガンプラやミリタリーモデルなどのプラモデルに留まらず、フィギュア（ガレージキット）やミニチュアハウスなど、思い思いの模型活動に取り組んでいます。</p>

<h2>活動内容</h2>
<p>定例制作会や学内展示のほか、他大学との合同制作会や学外展示イベントへの参加を行っています。</p>

<h2>入会案内</h2>
<p>九州産業大学 中央会館 7階 702 までお越しください。X(旧twitter)やinstagram、LINEオープンチャットからご一報いただけるとスムーズです。なお、原則学外の方の入会は受け付けておりませんのでご了承ください。</p>
