<h2>第3条（アカウントの管理と利用資格）</h2>
<p>本サイトの投稿機能およびログイン機能を利用できるのは、原則として当サークルの現役部員および当サークルが認めたOB/OG（以下「会員」といいます）に限るものとします。</p>
<p>会員は、自己の責任においてアカウント情報（ID・パスワード等）を管理するものとし、これを第三者に利用させ、または貸与、譲渡、売買等をしてはならないものとします。</p>
<p>運営者は、アカウント情報の管理不十分による損害について、一切の責任を負いません。</p>
<p>利用者が本規約に違反したと運営者が判断した場合、運営者は事前の通知なく当該アカウントを停止または削除できるものとします。</p>

<h2>第4条（卒業・退部に伴う休止会員としての扱い）</h2>
<p>会員が卒業、退部等により当サークルの現役部員でなくなった場合、原則として当該会員のアカウントは「休止会員」となります。休止会員は、新規投稿および会員プロフィールの編集を行うことはできません。</p>
<p>ただし、休止会員となった後も、ログイン、パスワードの再設定、および自己が既に投稿した内容の編集・削除は、引き続き行うことができるものとします。</p>
<p>休止会員が本人の希望によりアカウントの削除を申し出た場合、運営者は当該アカウント（投稿・画像を含みます）を削除するものとします。申し出がない場合、アカウントおよび既存の投稿は休止会員として保持されます。</p>

<h2>第5条（投稿内容の権利と利用許諾）</h2>
<p>会員が本サイトに投稿・アップロードする画像、文章等の著作権その他の権利は、当該投稿者本人が保持するものとします。</p>
<p>投稿者は、本サイトに対し、投稿コンテンツを日本の国内外において無償かつ非独占的に使用する権利（複製、公衆送信、展示、頒布等を含みます）を許諾するものとし、運営者およびサークルの広報活動（SNS、パンフレット、展示会等での紹介）において、これらを無償で利用できるものとします。</p>
<p>本サイトの投稿機能には、投稿者自身の操作によりアップロード画像にサークルのロゴを合成する機能があります。投稿者は、自己の操作により当該画像が加工された上で本サイトに掲載されることについて、あらかじめ同意するものとします。</p>
<p>投稿者は、第三者の著作権、商標権、プライバシー権、肖像権その他の権利を侵害する内容の投稿をしてはならないものとします。万一、第三者との間で紛争が生じた場合は、投稿者自身の責任と費用において解決するものとします。</p>
<p>投稿者は、投稿する模型写真等に含まれるキャラクター等の知的財産権に関して、第三者の権利を侵害しないよう十分配慮するものとします。また、投稿された作品（オリジナルの改造・塗装等を含む）の著作権は投稿者に帰属しますが、投稿者は当該作品が第三者の権利を侵害していないことを保証するものとします。</p>

