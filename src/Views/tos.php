<h2>第7条（個人情報等の取扱い）</h2>
<p>運営者は、会員登録および本サイトの利用に伴い、表示名、ログインID、会員が任意で入力したプロフィール、お問い合わせフォームに入力された内容（メールアドレスを含みます）等の情報を取得します。</p>
<p>会員が任意で入力したプロフィールは、会員ページにおいて訪問者を含む第三者に公開されます。学年・専攻等、公開を望まない情報については、会員自身の判断で入力しないものとします。</p>
