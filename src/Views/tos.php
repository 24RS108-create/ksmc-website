<h1>利用規約</h1>

<h2>第1条（適用）</h2>
<p>本規約は、九産模型愛好会公式サイト（以下「本サイト」といいます）が提供するすべてのサービス（模型ギャラリーへの画像投稿、公式ブログ、お問い合わせ等を含む）の利用条件を定めるものです。</p>
<p>本サイトを利用するすべてのユーザー（以下「利用者」といいます）は、本規約に同意した上で、本サイトを利用するものとします。</p>

<h2>第2条（運営者・お問い合わせ）</h2>
<p>運営者：九産模型愛好会　（九州産業大学公認：任意団体愛好会）</p>
